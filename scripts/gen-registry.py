#!/usr/bin/env python3
"""Regenerate `rust/lemans-verify/src/registry.rs` from `src/ports/*.rs`.

One file per ported function, named `p_<address>.rs`, exporting `pub fn run`.
Keeping the table generated removes the only shared file from the porting loop,
so several ports can land without touching the same lines.

Usage: scripts/gen-registry.py [--check]
  --check  exit 1 if registry.rs is stale (used by CI / the batch loop)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PORTS = ROOT / "rust/lemans-verify/src/ports"
REGISTRY = ROOT / "rust/lemans-verify/src/registry.rs"

NAME = re.compile(r"^p_([0-9a-f]{8})\.rs$")

HEADER = """\
//! Registry of ported functions, keyed by their original SH-4 address.
//!
//! Generated by `scripts/gen-registry.py` from `src/ports/p_<address>.rs`.
//! Do not edit by hand: add a file and re-run the generator.
//!
//! A port is a function that mutates `Cpu` and `Memory` exactly as the original
//! routine did: registers, FPU state and every store. Nothing else is allowed —
//! no hidden state, no I/O, no allocator.

use sh4_oracle::{Cpu, Memory};

pub type Port = fn(&mut Cpu, &mut Memory);
"""


def ports():
    found = []
    for path in sorted(PORTS.glob("p_*.rs")):
        m = NAME.match(path.name)
        if not m:
            raise SystemExit(f"bad port filename: {path.name} (want p_<8 hex>.rs)")
        found.append((int(m.group(1), 16), path.stem))
    return found


def render(entries):
    out = [HEADER]
    for _, stem in entries:
        out.append(f'#[path = "ports/{stem}.rs"]\npub mod {stem};')
    out.append("")
    out.append("pub fn lookup(address: u32) -> Option<Port> {")
    out.append("    match address {")
    for addr, stem in entries:
        out.append(f"        0x{addr:08X} => Some({stem}::run),")
    out.append("        _ => None,")
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def main(argv):
    entries = ports()
    text = render(entries)
    if "--check" in argv:
        current = REGISTRY.read_text() if REGISTRY.exists() else ""
        if current != text:
            print(f"registry.rs is stale ({len(entries)} ports)", file=sys.stderr)
            return 1
        return 0
    REGISTRY.write_text(text)
    print(f"registry.rs: {len(entries)} ports")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
